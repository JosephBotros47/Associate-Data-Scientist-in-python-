### ------- Arthemitic Operators --------
## [+] Addition
print(10+2)     #12
print(10.4+2.6) #13
print(-10+2.4)   #-7.6
print(1+2+3+4)  #10

## [-] Subtraction
print(10-2)  #8
print(-4-2)  #-6
print(10-2.2)#7.8

## [*] Multiplication
print(10*2)
print(2*2*2*2)
print(1*1*1*2)
# has priority than - , +
print(2+4-2*3) # 2*3 berfore 2+4 then 6-6  so equal zero
print(((2+4)-2)*3)# after putting brackets 2+4 then 6-2 then 4*3 so equal 12

## [%] modules 
print(10%2) #0
print(11%2) #1
print(12%2) #0
print(22%5) #2

## Exponent
print(2**5)# means 2*2*2*2*2
print(2*2*2*2*2)
print(5**4)# means 5*5*5*5
print(5*5*5*5)

# floor division don't take the fraction value 
print(100//20)#100/20 = 5 so the value is 5
print(110//20)#110/20 = 5.5 so the value is 5
print(119//20)#119/20 = 5.95 so the value is 5
print(120//20)#120/20 = 6 so the value is 6